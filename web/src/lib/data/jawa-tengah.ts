/** Get all kabupaten names */
export function getKabupatenList(): string[] {
  return JAWA_TENGAH_LOCATIONS.map((loc) => loc.kabupaten);
}

/** Get kecamatan list for a given kabupaten */
export function getKecamatanList(kabupaten: string): string[] {
  const loc = JAWA_TENGAH_LOCATIONS.find((l) => l.kabupaten === kabupaten);
  return loc?.kecamatan ?? [];
}
